def normalize_notebook(nb,name):
    kind=Path(name).name[:2]
    for i,cell in enumerate(nb['cells']):
        was_list=isinstance(cell['source'],list)
        text=''.join(cell['source']) if was_list else cell['source']
        if cell['cell_type']=='markdown':
            text=text.replace('真实图像训练结果见03','真实图像训练结果见02').replace('真实模型训练与召回率结果见03','真实模型训练与召回率结果见02').replace('真实人脸模型对照见03','真实人脸模型对照见02')
            if i==0:text=INTRO.get(kind,text)
            elif kind=='02' and i in IMAGE_SECTIONS:text=IMAGE_SECTIONS[i]
            else:
                text=text.replace('独立实现','按公式实现').replace('本组独立扩展，绝非AffectNet/ResNet50结果','补充合成实验，不属于AffectNet/ResNet50结果')
                text=text.replace('本组独立扩展，绝非 AffectNet/ResNet50 结果','补充合成实验，不属于AffectNet/ResNet50结果')
                if kind=='01' and text.startswith('## 结果判定'):
                    text='''## 结果对照

单组件指标与作者实现对照，并检查论文图中的数值与相关系数。结果见 `results/tables/paper_comparison.csv`。

本笔记展示20个数据集的表征和全局指标、60套局部矩阵的分析、正文图表和附录构造。个别汇总数字受聚合与并列处理方式影响，具体差异单独保留。'''
                if kind=='01' and text.startswith('## 附录'):
                    text='''## 附录A：四种受控偏差的计数与指标

重建Table III–VI：整体性别比例、仅happy类、happy/angry反向与同向变化；比例0–1，步长0.1。遵循相同的类别规模与取整规则。

单性别端点的关联指标按未定义值处理。这里计算数据指标，真实模型训练与召回率结果见02。'''
                if kind=='03' and text.startswith('## 怎样解读改进结果'):
                    text='''## 改进结果的解释

固定群体空间能揭示遗漏组合；在满足样本支持时，重加权可以调整统计分布。在合成模型中另外检查分布变化的影响，真实人脸模型对照见02。

同时报告有效样本量、准确率与分组召回率，以比较收益和代价。统计关联降低不直接等同于模型或因果公平。'''
        if cell['cell_type']=='code' and i in CODE_COMMENTS.get(kind,{}):
            comment='# '+CODE_COMMENTS[kind][i]
            if not text.startswith(comment):text=comment+'\n'+text
        cell['source']=text.splitlines(True) if was_list else text
    return nb
